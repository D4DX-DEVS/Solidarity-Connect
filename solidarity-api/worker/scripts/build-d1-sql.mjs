// Converts a MongoDB EJSON export (export-mongo.mjs) into D1 SQL.
//   node --import ./worker/dev/register.mjs worker/scripts/build-d1-sql.mjs <exportDir>
// Writes:
//   worker/migrations/0001_init.sql   tables + indexes for every model (and legacy collections with data)
//   <exportDir>/d1-data.sql            INSERTs for every document
//   <exportDir>/storage-form.json      { collection: [storage-form docs] } for verification
//   <exportDir>/r2-objects.json        Spaces objects referenced by the data → R2 keys
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { EJSON } from 'bson';
import mongoose from 'mongoose';
import { decodeUploadName } from '../../src/utils/fileName.js';

const exportDir = process.argv[2];
if (!exportDir || !fs.existsSync(exportDir)) {
  console.error('usage: build-d1-sql.mjs <exportDir>');
  process.exit(1);
}

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..', '..');
const modelsDir = path.join(root, 'src', 'models');
for (const f of fs.readdirSync(modelsDir).filter((n) => n.endsWith('.js'))) {
  await import(pathToFileURL(path.join(modelsDir, f)).href);
}
const models = Object.values(mongoose.models);
const modelTables = new Set(models.map((M) => M.collection.name));

const SPACES_URL = /^https:\/\/d4dx-storage\.blr1\.(?:cdn\.)?digitaloceanspaces\.com\/(.+)$/;
const r2Objects = new Map();

/**
 * BSON value → JSON storage form (ObjectId → hex, Date → ISO, Spaces URL → /cdn/<key>,
 * and upload file names that were stored as Latin-1 mojibake → proper UTF-8).
 */
function toStorage(v) {
  if (v === null || v === undefined) return v;
  if (v instanceof Date) return Number.isNaN(v.getTime()) ? null : v.toISOString();
  if (Array.isArray(v)) return v.map((el) => (el === undefined ? null : toStorage(el)));
  if (typeof v === 'object') {
    switch (v._bsontype) {
      case 'ObjectId':
      case 'ObjectID':
        return v.toHexString();
      case 'Decimal128':
        return Number(v.toString());
      case 'Long':
        return v.toNumber();
      case 'Int32':
      case 'Double':
        return v.valueOf();
      case 'Binary':
        return Buffer.from(v.buffer).toString('base64');
      case 'BSONRegExp':
        return `/${v.pattern}/${v.options}`;
      default:
        break;
    }
    const out = {};
    for (const [k, val] of Object.entries(v)) {
      if (val === undefined) continue;
      out[k] = k === 'originalName' ? decodeUploadName(toStorage(val)) : toStorage(val);
    }
    return out;
  }
  if (typeof v === 'string') {
    const m = v.match(SPACES_URL);
    if (m) {
      const key = decodeURIComponent(m[1].split(/[?#]/)[0]);
      r2Objects.set(key, v);
      return `/cdn/${key}`;
    }
  }
  return v;
}

const sqlString = (s) => `'${String(s).replace(/'/g, "''")}'`;

const ddl = [];
for (const M of models) ddl.push(...mongoose.ddlFor(M));

const data = [];
const storageForm = {};
const counts = {};
const files = fs.readdirSync(exportDir).filter((f) => f.endsWith('.json') && !f.startsWith('_') && !['storage-form.json', 'r2-objects.json'].includes(f));
for (const file of files) {
  const name = file.replace(/\.json$/, '');
  const docs = EJSON.parse(fs.readFileSync(path.join(exportDir, file), 'utf8'), { relaxed: false });
  if (!docs.length) continue;
  if (!modelTables.has(name)) {
    ddl.push(`CREATE TABLE IF NOT EXISTS "${name}" (_id TEXT PRIMARY KEY NOT NULL, doc TEXT NOT NULL CHECK (json_valid(doc)));`);
  }
  const converted = docs.map(toStorage);
  storageForm[name] = converted;
  counts[name] = converted.length;
  for (const doc of converted) {
    data.push(`INSERT INTO "${name}" (_id, doc) VALUES (${sqlString(String(doc._id))}, ${sqlString(JSON.stringify(doc))});`);
  }
}

const migrationsDir = path.join(root, 'worker', 'migrations');
fs.mkdirSync(migrationsDir, { recursive: true });
fs.writeFileSync(path.join(migrationsDir, '0001_init.sql'), `-- Generated by worker/scripts/build-d1-sql.mjs from the mongoose models.\n${ddl.join('\n')}\n`);
fs.writeFileSync(path.join(exportDir, 'd1-data.sql'), `${data.join('\n')}\n`);
fs.writeFileSync(path.join(exportDir, 'storage-form.json'), JSON.stringify(storageForm));
fs.writeFileSync(path.join(exportDir, 'r2-objects.json'), JSON.stringify([...r2Objects].map(([key, sourceUrl]) => ({ key, sourceUrl })), null, 2));

console.log(JSON.stringify({ tables: ddl.filter((s) => s.startsWith('CREATE TABLE')).length, indexes: ddl.filter((s) => s.includes('INDEX')).length, rows: data.length, counts, r2Objects: r2Objects.size }, null, 2));
